def materials_flat() -> list[tuple[str, str, str]]:
    """展平为 [(名称, 分类, 来源), ...]，共 400 种。"""
    out: list[tuple[str, str, str]] = []
    for cat, items in MATERIALS_GENSHIN.items():
        for name, source in items:
            out.append((name, cat, source))
    return out


UPGRADE_CATS = {"天赋书", "角色突破素材", "角色特产", "武器突破素材", "周本材料", "经验与货币"}


def assert_counts() -> None:
    flat = materials_flat()
    total = len(flat)
    upgrade = sum(1 for _, cat, _ in flat if cat in UPGRADE_CATS)
    assert total == 400, f"材料应为 400 种，当前 {total}"
    assert upgrade >= 200, f"升级相关材料应 ≥200 种，当前 {upgrade}"


if __name__ == "__main__":
    assert_counts()
    print(f"材料总数 {len(materials_flat())}，"
          f"升级相关 {sum(1 for _, c, _ in materials_flat() if c in UPGRADE_CATS)} 种")
