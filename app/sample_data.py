def lines_for(game_name: str) -> list[str]:
    """把某游戏的示例账户转成模拟 OCR 文本行。"""
    s = SAMPLE[game_name]
    lines = [f"{name} Lv.{lv}" for name, lv in s["characters"]]
    lines += [f"{name} Lv.{lv}" for name, lv in s["weapons"]]
    lines += [f"{setname}（{stat}）{slot}" for setname, stat, slot in s["equipment"]]
    lines += s["materials"]
    return lines
