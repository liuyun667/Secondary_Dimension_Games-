def _graduation_tiers(substats: list[str]) -> dict:
    """每角色专属 3 档毕业要求（休闲/标准/极限）：等级、武器、副词条目标、技能等级逐档提升。

    数据口径参考米游社/玩家社区常见毕业线：
    - 休闲：角色 80 级、武器 80、词条目标 ~60%、技能 8/8/8
    - 标准：角色 90 级、武器 90、词条目标 100%、技能 9/9/9
    - 极限：角色 90 级、武器 90、词条目标 ~120%、技能 10/10/10（皇冠）
    """
    base = {s: SUBSTAT_TARGET.get(s, 1) for s in substats}

    def scale(f: float) -> dict:
        return {k: max(1, int(v * f)) for k, v in base.items()}

    return {
        "casual": {"level": 80, "weapon": {"min_level": 80},
                   "substat_targets": scale(0.6),
                   "talents": {"normal": 8, "skill": 8, "burst": 8}},
        "standard": {"level": 90, "weapon": {"min_level": 90},
                     "substat_targets": base,
                     "talents": {"normal": 9, "skill": 9, "burst": 9}},
        "extreme": {"level": 90, "weapon": {"min_level": 90},
                    "substat_targets": scale(1.2),
                    "talents": {"normal": 10, "skill": 10, "burst": 10}},
    }


def _graduation_from_build(build: tuple) -> dict:
    name, weapons, setname, main_stats, substats = build
    focus = KEY_STATS.get(name, substats)      # 该角色关注属性（其余属性视为无用，不参与评估）
    return {
        "level": 90,
        "talents": {"normal": 9, "skill": 9, "burst": 9},   # 技能等级目标：普攻/元素战绩/元素爆发
        "talent_priority": _talent_priority(name),
        "weapon": {"min_level": 90, "best": weapons},
        "artifact_set": [setname],
        "main_stats": main_stats,
        "substat_targets": {s: SUBSTAT_TARGET.get(s, 1) for s in focus},
        "tiers": _graduation_tiers(focus),                  # 每角色专属 3 档（休闲/标准/极限）
    }


