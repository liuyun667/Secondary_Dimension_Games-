def _merged(code: str) -> dict:
    """基础 DATA 与 kb_expand.EXTRA 合并（扩充实体/配装）。"""
    d = json.loads(json.dumps(DATA[code]))
    ex = kb_expand.EXTRA.get(code, {})
    for key in ("characters", "weapons", "equipment", "builds"):
        d[key] = d.get(key, []) + ex.get(key, [])
    return d


def seed_all() -> None:
    db.init_db()
    cur = db.query_one("SELECT adapter_key FROM game WHERE code='genshin'")
    if cur and cur["adapter_key"] == f"genshin_{SEED_VERSION}":
        return  # 已初始化且版本一致
    if cur:
        # 数据版本过期：清空后重建（开发阶段；会重置用户账户数据）
        for t in ("user_feedback", "team_graduate", "user_standard", "user_asset",
                  "ocr_sample", "kb_team", "kb_graduation", "kb_build", "entity",
                  "game"):
            db.execute(f"DELETE FROM {t}")

    for code, name, weapon_name, equipment_name, max_team_size in GAMES:
        gid = db.execute(
            "INSERT INTO game (code, name, weapon_name, equipment_name, adapter_key, "
            "max_team_size) VALUES (?,?,?,?,?,?)",
            (code, name, weapon_name, equipment_name, f"{code}_{SEED_VERSION}",
             max_team_size))
        data = _merged(code)

        name_to_id: dict[str, int] = {}
        for cname, aliases, rarity in data["characters"]:
            name_to_id[cname] = _insert_entity(gid, "角色", cname, aliases, rarity)
        for wname, aliases, rarity in data["weapons"]:
            name_to_id[wname] = _insert_entity(gid, "武器", wname, aliases, rarity)
        for sname, aliases, rarity in data["equipment"]:
            name_to_id[sname] = _insert_entity(gid, "装备", sname, aliases, rarity)

        # 武器固有属性知识库（原神 100 件真实数据：类型/基础攻击/主词条/被动）
        if code == "genshin":
            from .kb_weapons import WEAPONS_GENSHIN
            for wname, rarity, wtype, base_atk, mstat, mval, passive in WEAPONS_GENSHIN:
                if wname not in name_to_id:
                    name_to_id[wname] = _insert_entity(gid, "武器", wname, [], rarity)
                db.execute(
                    "INSERT OR REPLACE INTO kb_weapon (entity_id, game_id, weapon_type, "
                    "base_atk, main_stat, main_stat_value, passive) VALUES (?,?,?,?,?,?,?)",
                    (name_to_id[wname], gid, wtype, base_atk, mstat, mval, passive))
            # DATA 里引用但不在 100 件库中的武器（如 苍翠猎弓）：按星级补占位属性
            for wname, eid in name_to_id.items():
                ent = db.query_one("SELECT type FROM entity WHERE id=?", (eid,))
                if ent and ent["type"] == "武器" and not db.query_one(
                        "SELECT 1 FROM kb_weapon WHERE entity_id=?", (eid,)):
                    rarity = db.query_one("SELECT rarity FROM entity WHERE id=?", (eid,))["rarity"]
                    base = 608 if rarity == 5 else 510
                    db.execute(
                        "INSERT OR REPLACE INTO kb_weapon (entity_id, game_id, weapon_type, "
                        "base_atk, main_stat, main_stat_value, passive) VALUES (?,?,?,?,?,?,?)",
                        (eid, gid, "未知", base, "攻击力", 49.6 if rarity == 5 else 41.3,
                         "未知"))

        for build in data["builds"]:
            cname, weapons, setname, main_stats, substats = build
            char_id = name_to_id[cname]
            db.execute(
                "INSERT INTO kb_build (game_id, char_id, weapon_ids, artifact_ids, "
                "main_stats, substat_priority, version, source, review_status) "
                "VALUES (?,?,?,?,?,?,?,?,?)",
                (gid, char_id,
                 json.dumps([name_to_id[w] for w in weapons], ensure_ascii=False),
                 json.dumps([name_to_id[setname]], ensure_ascii=False),
                 json.dumps(main_stats, ensure_ascii=False),
                 json.dumps(substats, ensure_ascii=False),
                 "1.0", "社区聚合", "已审核"))
            db.execute(
                "INSERT INTO kb_graduation (game_id, char_id, criteria, version, status) "
                "VALUES (?,?,?,?,?)",
                (gid, char_id,
                 json.dumps(_graduation_from_build(build), ensure_ascii=False),
                 "1.0", "生效"))

        for tname, members, synergy in data["teams"]:
            db.execute(
                "INSERT INTO kb_team (game_id, name, member_ids, synergy, version) "
                "VALUES (?,?,?,?,?)",
                (gid, tname,
                 json.dumps([name_to_id[m] for m in members], ensure_ascii=False),
                 json.dumps({"简介": synergy}, ensure_ascii=False), "1.0"))

        _gen_recipes(gid, name_to_id)  # 升级配方（角色升级/技能/武器升级）
